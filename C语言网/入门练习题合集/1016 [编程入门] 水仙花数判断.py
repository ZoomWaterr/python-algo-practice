#如何输出所有的数字
#题中给到，是一个三位数，所以有了界限
for i in range(100,1000):   #那获取每个数的位数是个问题
    #a = i // 100 #取百位
    list1 = list(str(i)) #把数字转成字符串分别存到列表里
    if int(list1[0]) **3 + int(list1[1]) **3 + int(list1[2]) **3 == i:
        print(i)

for i in range(100,1000):
    i1 = i // 100   #取百位
    i2 = (i % 100) // 10    #先手取余剩下十位和个位，然后整除10取到十位
    i3 = (i % 10)   #对10取余这就是个位数了
    if i == i1 **3 + i2 **3 + i3 **3:
        print(i)